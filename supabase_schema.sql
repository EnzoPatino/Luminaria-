-- 1. TABLA: zona
CREATE TABLE IF NOT EXISTS public.zona (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL
);

-- 2. TABLA: tablero
CREATE TABLE IF NOT EXISTS public.tablero (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_zona INTEGER NOT NULL REFERENCES public.zona(id) ON DELETE CASCADE,
  codigo VARCHAR(50) UNIQUE,
  nombre VARCHAR(150),
  ubicacion TEXT,
  pos_x REAL DEFAULT 50,
  pos_y REAL DEFAULT 50,
  fase VARCHAR(10) DEFAULT 'L1',
  tension_nominal NUMERIC(6,2) NOT NULL DEFAULT 220.00,
  tension_medida_v NUMERIC(6,2) NOT NULL DEFAULT 220.00,
  estado VARCHAR(20) NOT NULL DEFAULT 'ok',
  focos JSONB NOT NULL DEFAULT '{}'::jsonb,
  ultima_modificacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 3. TABLA: sensor
CREATE TABLE IF NOT EXISTS public.sensor (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_tablero INTEGER NOT NULL REFERENCES public.tablero(id) ON DELETE CASCADE,
  mac VARCHAR(50) NOT NULL UNIQUE,
  ultima_modificacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 4. TABLA: lectura
CREATE TABLE IF NOT EXISTS public.lectura (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sensor INTEGER NOT NULL REFERENCES public.sensor(id) ON DELETE CASCADE,
  id_tablero INTEGER NOT NULL REFERENCES public.tablero(id) ON DELETE CASCADE,
  amperaje NUMERIC NOT NULL,
  tension_v NUMERIC(6,2) DEFAULT 220.00,
  fase VARCHAR(10) DEFAULT 'L1',
  fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 5. TABLA: tecnico
CREATE TABLE IF NOT EXISTS public.tecnico (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(50) NOT NULL,
  apellido VARCHAR(50) NOT NULL,
  dni VARCHAR(15) NOT NULL UNIQUE,
  telefono VARCHAR(20),
  email VARCHAR(100) UNIQUE,
  usuario VARCHAR(50) NOT NULL UNIQUE,
  contrasenia VARCHAR(255) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 6. TABLA: admin
CREATE TABLE IF NOT EXISTS public.admin (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL,
  apellido VARCHAR(50) NOT NULL,
  usuario VARCHAR(50) NOT NULL UNIQUE,
  contrasenia VARCHAR(255) NOT NULL,
  dni VARCHAR(15) NOT NULL UNIQUE,
  telefono VARCHAR(20),
  email VARCHAR(100) UNIQUE,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 7. TABLA: alerta
CREATE TABLE IF NOT EXISTS public.alerta (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lectura INTEGER REFERENCES public.lectura(id) ON DELETE SET NULL,
  id_tablero INTEGER NOT NULL REFERENCES public.tablero(id) ON DELETE CASCADE,
  id_tecnico INTEGER REFERENCES public.tecnico(id) ON DELETE SET NULL,
  tipo VARCHAR(50) NOT NULL,
  prioridad VARCHAR(20) NOT NULL,
  estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
  fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now(),
  titulo VARCHAR(255),
  ubicacion TEXT,
  datos_json JSONB DEFAULT '{}'::jsonb,
  tecnico_resolucion VARCHAR(150),
  fecha_resolucion TIMESTAMPTZ
);

-- 8. TABLA: gestiona (Relación N:M entre admin y tecnico según DER)
CREATE TABLE IF NOT EXISTS public.gestiona (
  id_admin INTEGER NOT NULL REFERENCES public.admin(id) ON DELETE CASCADE,
  id_tecnico INTEGER NOT NULL REFERENCES public.tecnico(id) ON DELETE CASCADE,
  fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id_admin, id_tecnico)
);

-- Vista/Sinónimo admin_tecnico para compatibilidad
CREATE OR REPLACE VIEW public.admin_tecnico WITH (security_invoker = true) AS
SELECT id_admin, id_tecnico, fecha_asignacion FROM public.gestiona;

-- 9. AUDIT_LOG
CREATE TABLE IF NOT EXISTS public.audit_log (
  id_audit BIGSERIAL PRIMARY KEY,
  timestamp TIMESTAMPTZ NOT NULL DEFAULT now(),
  id_usuario INTEGER,
  accion TEXT NOT NULL,
  recurso TEXT NOT NULL,
  id_recurso TEXT,
  ip_origen TEXT,
  detalles JSONB,
  correlation_id TEXT
);


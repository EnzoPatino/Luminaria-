-- ====================================================================
-- VISTAS DE COMPATIBILIDAD PLURAL PARA LA UI Y CONSUMO REST (SECURITY INVOKER)
-- ====================================================================
CREATE OR REPLACE VIEW public.tableros WITH (security_invoker = true) AS 
SELECT 
  id,
  coalesce(codigo, 'TABLERO_' || lpad(id::text, 2, '0')) AS id_tablero,
  nombre AS nombre_tablero,
  ubicacion,
  pos_x,
  pos_y,
  fase,
  tension_nominal,
  tension_medida_v,
  estado,
  focos,
  ultima_modificacion AS ultima_actualizacion
FROM public.tablero;

CREATE OR REPLACE VIEW public.alertas WITH (security_invoker = true) AS
SELECT
  id AS id_alerta,
  coalesce((SELECT codigo FROM public.tablero WHERE tablero.id = alerta.id_tablero), 'TABLERO_' || lpad(id_tablero::text, 2, '0')) AS id_tablero,
  id_tablero AS id_tablero_num,
  tipo AS tipo_evento,
  prioridad,
  titulo,
  ubicacion,
  datos_json,
  estado AS estado_alerta,
  fecha_hora AS fecha_hora_generada,
  fecha_resolucion,
  tecnico_resolucion
FROM public.alerta;

-- Vista unificada de usuarios para autenticación
CREATE OR REPLACE VIEW public.usuarios WITH (security_invoker = true) AS
SELECT 
  id AS id_usuario,
  id,
  nombre,
  apellido,
  dni,
  telefono,
  usuario,
  email,
  contrasenia AS password_hash,
  'admin'::text AS rol,
  activo,
  created_at
FROM public.admin
UNION ALL
SELECT 
  id AS id_usuario,
  id,
  nom AS nombre,
  apellido,
  dni,
  telefono,
  usuario,
  email,
  contrasenia AS password_hash,
  'tecnico'::text AS rol,
  activo,
  created_at
FROM public.tecnico;

-- Triggers INSTEAD OF para permitir INSERT / UPDATE sobre las vistas
CREATE OR REPLACE FUNCTION public.trg_alertas_view_insert()
RETURNS TRIGGER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_id_tablero integer;
BEGIN
  IF NEW.id_tablero ~ '^[0-9]+$' THEN
    v_id_tablero := NEW.id_tablero::integer;
  ELSE
    SELECT id INTO v_id_tablero FROM public.tablero WHERE codigo = NEW.id_tablero LIMIT 1;
    IF v_id_tablero IS NULL THEN
      SELECT id INTO v_id_tablero FROM public.tablero WHERE id = NULLIF(regexp_replace(NEW.id_tablero, '[^0-9]', '', 'g'), '')::integer LIMIT 1;
    END IF;
  END IF;
  
  IF v_id_tablero IS NULL THEN
    v_id_tablero := 1;
  END IF;

  INSERT INTO public.alerta (
    id_tablero, tipo, prioridad, estado, fecha_hora, titulo, ubicacion, datos_json, tecnico_resolucion, fecha_resolucion
  ) VALUES (
    v_id_tablero,
    COALESCE(NEW.tipo_evento, 'ALERTA'),
    COALESCE(NEW.prioridad, 'INFO'),
    COALESCE(NEW.estado_alerta, 'pendiente'),
    COALESCE(NEW.fecha_hora_generada, now()),
    NEW.titulo,
    NEW.ubicacion,
    COALESCE(NEW.datos_json, '{}'::jsonb),
    NEW.tecnico_resolucion,
    NEW.fecha_resolucion
  ) RETURNING id INTO NEW.id_alerta;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_alertas_insert ON public.alertas;
CREATE TRIGGER trg_alertas_insert
INSTEAD OF INSERT ON public.alertas
FOR EACH ROW EXECUTE FUNCTION public.trg_alertas_view_insert();

CREATE OR REPLACE FUNCTION public.trg_alertas_view_update()
RETURNS TRIGGER
SET search_path = public, pg_temp
AS $$
BEGIN
  UPDATE public.alerta
  SET 
    estado = COALESCE(NEW.estado_alerta, estado),
    fecha_resolucion = COALESCE(NEW.fecha_resolucion, fecha_resolucion),
    tecnico_resolucion = COALESCE(NEW.tecnico_resolucion, tecnico_resolucion)
  WHERE id = NEW.id_alerta;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_alertas_update ON public.alertas;
CREATE TRIGGER trg_alertas_update
INSTEAD OF UPDATE ON public.alertas
FOR EACH ROW EXECUTE FUNCTION public.trg_alertas_view_update();

CREATE OR REPLACE FUNCTION public.trg_tableros_view_update()
RETURNS TRIGGER
SET search_path = public, pg_temp
AS $$
BEGIN
  UPDATE public.tablero
  SET
    tension_medida_v = COALESCE(NEW.tension_medida_v, tension_medida_v),
    estado = COALESCE(NEW.estado, estado),
    focos = COALESCE(NEW.focos, focos),
    ultima_modificacion = now()
  WHERE codigo = NEW.id_tablero OR id::text = NEW.id_tablero;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_tableros_update ON public.tableros;
CREATE TRIGGER trg_tableros_update
INSTEAD OF UPDATE ON public.tableros
FOR EACH ROW EXECUTE FUNCTION public.trg_tableros_view_update();

